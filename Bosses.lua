for i, e in ipairs(ENCS) do
	for _, id in ipairs(e.ids) do
		ENC[id] = i
		BOSS[id] = true
	end
	if e.kill then
		local set, n = {}, 0
		for _, id in ipairs(e.kill) do
			set[id] = true
			n = n + 1
		end
		e.kill, e.need = set, e.all and n or 1
	end
	e.ids = nil
end

-- Identifiant de créature contenu dans un identifiant d'unité 3.3.5
-- ("0xF130" + 6 chiffres d'identifiant + 6 chiffres d'apparition). Le 5e
-- caractère donne le type : 3 créature, 5 véhicule ; un joueur (0) ou un
-- familier (4) n'en a pas, et ses chiffres pourraient imiter un boss.
local CREATURE_TYPES = { ["3"] = true, ["5"] = true }
function Z.CreatureId(guid)
	if type(guid) ~= "string" or #guid < 12 or not CREATURE_TYPES[guid:sub(5, 5)] then return nil end
	return tonumber(guid:sub(7, 12), 16)
end
